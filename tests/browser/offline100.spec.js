import {test,expect} from '@playwright/test';
import {connect,openId,screen} from './helpers.js';
const photo='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScL/nwAAAABJRU5ErkJggg==';
const details={id:55,title:'Старая башня',description:'История объекта.\nВторая строка.',photos:{photo:[{big_url:'https://photos.wikimapia.org/test.jpg',author_name:'Автор'}]},comments:{comment:[{name:'Читатель',message:'Тестовый комментарий'}]}};
test('explicit offline save keeps description, comments and local gallery after reload',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('wikimapia-reader-auto','false'));
  await page.route('https://tile.openstreetmap.org/**',r=>r.abort());
  await page.route('https://photos.wikimapia.org/**',r=>r.fulfill({status:200,contentType:'image/png',headers:{'Access-Control-Allow-Origin':'*'},body:Buffer.from(photo,'base64')}));
  await page.route('https://api.wikimapia.org/**',r=>r.fulfill({json:details}));
  await page.goto('/');await connect(page);await openId(page);
  await expect(page.locator('.description')).toContainText('Вторая строка');
  await page.getByRole('button',{name:'Действия с объектом'}).click();await page.getByRole('button',{name:'Сохранить для чтения без сети'}).click();
  await expect(page.getByRole('button',{name:'Удалить офлайн-копию'})).toBeVisible();
  await page.route('https://api.wikimapia.org/**',r=>r.abort());
  await page.route('https://photos.wikimapia.org/**',r=>r.abort());
  await page.addInitScript(()=>Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false}));
  await page.reload();
  await screen(page,'Избранное');
  await expect(page.locator('.offline-list')).toContainText('Старая башня');
  await page.locator('.offline-list .saved-open').click();
  await expect(page.locator('.description')).toContainText('История объекта.');
  await page.getByRole('tab',{name:/Фото/}).click();
  await expect(page.locator('.photos img')).toHaveAttribute('src',/^blob:/);
  await page.getByRole('button',{name:'Открыть фото 1'}).click();
  await expect(page.getByRole('dialog',{name:'Просмотр фотографий'})).toBeVisible();
  await page.getByRole('button',{name:'Закрыть галерею'}).click();
  await page.getByRole('tab',{name:/Комментарии/}).click();
  await expect(page.locator('.comment')).toContainText('Тестовый комментарий');
});
